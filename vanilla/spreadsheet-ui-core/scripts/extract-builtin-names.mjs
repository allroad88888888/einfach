#!/usr/bin/env node
/**
 * Extracts the master list of built-in formula names from the Rust
 * engine's `is_builtin_function_name` arms in
 * `rust/excel-core/src/eval.rs` and writes a sorted, de-duplicated
 * `string[]` TypeScript module.
 *
 * Run from any cwd:  node vanilla/spreadsheet-ui-core/scripts/extract-builtin-names.mjs
 *
 * The output file is committed; this script exists so the list stays
 * verifiable / re-generatable when the Rust engine adds new arms. The
 * UI's `BUILTIN_FORMULA_NAMES` Set is built from this generated list
 * AND from the IntelliSense seed registry so both sources stay in sync.
 *
 * NOTE: this script is intentionally dependency-free (uses only `fs` +
 * `path`) so it runs under any Node version the repo supports without
 * needing a separate `npm install`.
 */
import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const here = dirname(fileURLToPath(import.meta.url))
const repoRoot = resolve(here, '..', '..', '..')
const evalRsPath = resolve(repoRoot, 'rust', 'excel-core', 'src', 'eval.rs')
const outPath = resolve(here, '..', 'src', 'custom-formulas', 'engine-builtin-names.ts')

const src = readFileSync(evalRsPath, 'utf8')

// Locate the `pub fn is_builtin_function_name` block and capture only
// the body of its `matches!(...)` macro — restricted to keep us from
// accidentally pulling in unrelated identifier-literals elsewhere in
// the file.
const fnIdx = src.indexOf('pub fn is_builtin_function_name')
if (fnIdx === -1) {
  throw new Error('is_builtin_function_name not found in eval.rs')
}
// Scan forward to the closing `)` of the matches!(...) macro by tracking parens.
const matchesOpen = src.indexOf('matches!(', fnIdx)
if (matchesOpen === -1) {
  throw new Error('matches!(...) macro not found after is_builtin_function_name')
}
let depth = 0
let cursor = matchesOpen + 'matches!'.length
let matchesEnd = -1
for (; cursor < src.length; cursor++) {
  const ch = src[cursor]
  if (ch === '(') depth++
  else if (ch === ')') {
    depth--
    if (depth === 0) {
      matchesEnd = cursor
      break
    }
  }
}
if (matchesEnd === -1) {
  throw new Error('unbalanced matches!(...) parens')
}
const body = src.slice(matchesOpen, matchesEnd)

// Pull every `"NAME"` literal out of the macro body.
const names = Array.from(body.matchAll(/"([A-Z][A-Z0-9_.]*)"/g)).map((m) => m[1])
const unique = Array.from(new Set(names)).sort()

const header = `/**
 * Auto-generated by \`scripts/extract-builtin-names.mjs\`.
 *
 * DO NOT EDIT BY HAND. Re-run the script if \`rust/excel-core/src/eval.rs\`
 * adds or removes arms in \`is_builtin_function_name\`. Source of truth
 * for the JS-side shadow check lives in the Rust engine — this file is
 * a mirror, not an authority.
 *
 * Count: ${unique.length} names.
 */
export const ENGINE_BUILTIN_FORMULA_NAMES: readonly string[] = Object.freeze([
${unique.map((n) => `  '${n}',`).join('\n')}
])
`

writeFileSync(outPath, header)
process.stdout.write(`wrote ${unique.length} names -> ${outPath}\n`)
